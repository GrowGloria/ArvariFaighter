/// <summary>
/// Встроенный пиксельный шрифт 5x7 (латиница, кириллица, цифры). Только заглавные —
/// строчные буквы автоматически рисуются заглавными. Не требует Content Pipeline.
/// </summary>
public sealed class BitmapFont
{
    public const int GlyphW = 5, GlyphH = 7, Advance = 6;

    private readonly Texture2D _atlas;
    private readonly Dictionary<char, Rectangle> _rects = new();

    public int LineHeight => GlyphH + 2;

    public BitmapFont(GraphicsDevice device)
    {
        var glyphs = Glyphs();
        int cols = 16, rows = (glyphs.Count + cols - 1) / cols;
        int w = cols * GlyphW, h = rows * GlyphH;
        var data = new Color[w * h];
        int i = 0;
        foreach (var (ch, rowsStr) in glyphs)
        {
            int gx = i % cols * GlyphW, gy = i / cols * GlyphH;
            var lines = rowsStr.Split('|');
            for (int y = 0; y < GlyphH; y++)
                for (int x = 0; x < GlyphW; x++)
                    if (lines[y][x] == '#') data[(gy + y) * w + gx + x] = Color.White;
            _rects[ch] = new Rectangle(gx, gy, GlyphW, GlyphH);
            i++;
        }
        _atlas = new Texture2D(device, w, h);
        _atlas.SetData(data);
    }

    public int Measure(string text, int scale = 1) => text.Length == 0 ? 0 : (text.Length * Advance - 1) * scale;

    public void Draw(SpriteBatch batch, string text, int x, int y, Color color, int scale = 1)
    {
        int cx = x;
        foreach (var raw in text)
        {
            var ch = char.ToUpperInvariant(raw);
            if (ch != ' ')
            {
                if (!_rects.TryGetValue(ch, out var src)) src = _rects['?'];
                batch.Draw(_atlas, new Rectangle(cx, y, GlyphW * scale, GlyphH * scale), src, color);
            }
            cx += Advance * scale;
        }
    }

